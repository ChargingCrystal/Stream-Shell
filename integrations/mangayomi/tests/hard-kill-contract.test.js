const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'../../..');
const cs=fs.readFileSync(path.join(root,'integrations/mangayomi/StreamShellMangayomiHost.cs'),'utf8');
const start=cs.indexOf('static void HandleKill('), end=cs.indexOf('static void Main()',start);
assert.ok(start>0&&end>start,'dedicated Kill method (no Main scope collision)');
const body=cs.slice(start,end);
assert.match(body,/ConfiguredForkExe\(GetString\(json, "executablePath"\)\)/);
assert.match(body,/GetProcessesByName\("Mangayomi"\)/);
assert.match(body,/process\.MainModule|killProcess\.MainModule/);
assert.match(body,/taskkill\.exe/);
assert.match(body,/" \/T \/F"/);
assert.match(body,/!killProcess\.HasExited/);
assert.match(body,/FindApp\(killExe, false\)/);
assert.doesNotMatch(body,/ResolveExe\(/,'never fallback to an unconfigured app');
assert.match(cs.slice(end),/if \(action == "kill"\) \{ HandleKill\(json\); return; \}/);
const bg=fs.readFileSync(path.join(root,'background/src/05-mangayomi.js'),'utf8');
assert.match(bg,/action !== "hide" && action !== "kill"/,'shutdown works even after Seven Seas revoke');
const router=fs.readFileSync(path.join(root,'background/src/09-message-router.js'),'utf8');
assert.match(router,/message\.type === "dashboard-kill-mangayomi"[\s\S]*?isDashboardSender\(sender\)/);
assert.match(router,/killMangayomiByUserRequest\(\)/);
const ui=fs.readFileSync(path.join(root,'dashboard/src/settings-runtime.js'),'utf8');
assert.match(ui,/settings-mangayomi-kill/);
assert.match(ui,/window\.confirm\(/);
const shutdown=fs.readFileSync(path.join(root,'background/src/07-shutdown.js'),'utf8');
assert.match(shutdown,/await mangayomiNativeCommand\("kill"\)/, 'global skull kill also terminates external process');
console.log('Mangayomi native hard Kill: exact-path, explicit-confirmation, sender-gate contract: PASS (C# compile separate)');
