'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const runtime = fs.readFileSync(path.join(__dirname,'../src/settings-runtime.js'),'utf8');
const controls = fs.readFileSync(path.join(__dirname,'../src/settings-controls.js'),'utf8');
test('explanation toggle updates in place, keeps focus and does not save provider settings',()=>{
 const attrs={}; const classes=new Set();
 const button={hasAttribute:name=>name==='data-settings-help',setAttribute:(k,v)=>attrs[k]=v};
 const context=vm.createContext({settingsContent:{classList:{toggle:(k,v)=>v?classes.add(k):classes.delete(k)}}});
 vm.runInContext(controls,context);
 const start=runtime.indexOf('function handleSettingsClick(');
 const end=runtime.indexOf('\nfunction ',start+10);
 vm.runInContext(runtime.slice(start,end),context);
 context.event={target:{closest:()=>button}};
 assert.equal(vm.runInContext('handleSettingsClick(event)',context),true);
 assert.equal(attrs['aria-pressed'],'true');
 assert.equal(button.textContent,'Hide explanations');
 assert.ok(classes.has('settings-explanations-visible'));
 vm.runInContext('handleSettingsClick(event)',context);
 assert.equal(attrs['aria-pressed'],'false');
 assert.equal(button.textContent,'Show explanations');
 assert.equal(classes.size,0);
});
test('sidebar retains category labels and marks the selected destination',()=>{
 const sidebar={innerHTML:'',querySelectorAll:()=>[]};
 const context=vm.createContext({settingsCategoryOrder:{},settingsSidebar:sidebar,settingsProvider:'youtube',settingsSection:'audio',SETTINGS_SECTIONS:{youtube:[['audio','Audio'],['playback','Playback']]}});
 vm.runInContext(controls,context);
 const start=runtime.indexOf('function renderSettingsSidebar(');
 const end=runtime.indexOf('\nfunction ',start+10);
 vm.runInContext(runtime.slice(start,end),context);
 vm.runInContext('renderSettingsSidebar()',context);
 assert.match(sidebar.innerHTML,/data-settings-section="audio" aria-current="page"/);
 assert.match(sidebar.innerHTML,/<span>Audio<\/span>/);
 assert.match(sidebar.innerHTML,/aria-hidden="true"/);
 assert.match(sidebar.innerHTML,/data-settings-section="playback" aria-current="false"/);
});
